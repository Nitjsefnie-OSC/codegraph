/// Render a view's `{view}.spec.ts`. `include_personas` is false only when
/// the `ifml_e2e_auth` flag moved the persona coverage into the
/// `{view}.auth.spec.ts` family (issue #463); the inline `addInitScript`
/// persona blocks must not survive there. Flag off renders exactly the
/// historical output (personas included).
pub(crate) fn render_spec(spec: &ViewTestSpec, include_personas: bool) -> String {
    let class = format!("{}Page", to_pascal_case(&spec.view_name));
    let mut s = String::new();
    s.push_str("// Generated by codegraph. DO NOT EDIT.\n");
    s.push_str(&format!(
        "// IFML Playwright E2E tests for view {}.\n// All selectors live in the {} page class (issue #317).\n\n",
        spec.view_name, class
    ));
    s.push_str("import { test, expect } from '@playwright/test';\n\n");
    s.push_str(&format!(
        "import {{ {class} }} from '../pages/{}-page';\n\n",
        to_kebab_case(&spec.view_name)
    ));
    s.push_str(&format!(
        "test.describe('{}', () => {{\n",
        js_string(&spec.label)
    ));

    if let Some(render) = &spec.render {
        s.push_str(&format!(
            "\ttest('renders {}', async ({{ page }}) => {{\n",
            js_string(&render.label)
        ));
        s.push_str(&format!("\t\tconst ui = new {class}(page);\n"));
        s.push_str("\t\tawait ui.open();\n");
        if render.assert_heading {
            s.push_str("\t\tawait expect(ui.heading()).toBeVisible();\n");
        }
        s.push_str("\t\tawait expect(ui.primaryRoot()).toBeVisible();\n");
        if render.nav_testid.is_some() {
            s.push_str("\t\tawait expect(ui.navRoot()).toBeVisible();\n");
        }
        if render.container_testid.is_some() {
            s.push_str("\t\tawait expect(ui.containerRoot()).toBeVisible();\n");
        }
        s.push_str("\t});\n\n");
    }

    if include_personas {
        for persona in &spec.personas {
            let caps_lines = match &persona.capabilities {
                Some(caps) => format!(
                    "\t\t\t(globalThis as any).__USER_CAPABILITIES__ = [{}];\n",
                    caps.iter()
                        .map(|c| format!("'{}'", js_string(c)))
                        .collect::<Vec<_>>()
                        .join(", ")
                ),
                None => String::new(),
            };
            s.push_str(&format!(
                "\ttest('actor {} {} {}', async ({{ page }}) => {{\n",
                js_string(&persona.actor),
                if persona.permitted {
                    "views"
                } else {
                    "is redirected from"
                },
                js_string(&persona.label)
            ));
            s.push_str(&format!("\t\tconst ui = new {class}(page);\n"));
            s.push_str(&format!(
                "\t\tawait page.addInitScript(() => {{\n\t\t\t(globalThis as any).__USER_ROLES__ = [{}];\n{}\t\t}});\n",
                crate::ifml::route_generator::actor_role_tokens(&persona.actor)
                    .iter()
                    .map(|role| format!("'{}'", js_string(role)))
                    .collect::<Vec<_>>()
                    .join(", "),
                caps_lines
            ));
            s.push_str("\t\tawait ui.open();\n");
            if persona.permitted {
                if persona.assert_heading || persona.primary_testid.is_none() {
                    s.push_str("\t\tawait expect(ui.heading()).toBeVisible();\n");
                } else {
                    s.push_str("\t\tawait expect(ui.primaryRoot()).toBeVisible();\n");
                }
                if let Some(component) = &persona.control_component {
                    s.push_str(&format!(
                        "\t\tawait expect(ui.{component}Submit()).toBeVisible();\n"
                    ));
                }
            } else {
                s.push_str("\t\tawait ui.expectDenied();\n");
            }
            s.push_str("\t});\n\n");
        }
    }

    for flow in &spec.click_throughs {
        s.push_str(&format!(
            "\ttest('{}', async ({{ page, request }}) => {{\n",
            js_string(&flow.title)
        ));
        s.push_str(&format!("\t\tconst ui = new {class}(page);\n"));
        s.push_str(&format!(
            "\t\tconst fixture = await request.post('{}', {{ data: {} }});\n",
            flow.fixture.base_path,
            flow.fixture.data_literal()
        ));
        s.push_str("\t\texpect(fixture.ok(), 'fixture entity should be created').toBeTruthy();\n");
        s.push_str("\t\tawait ui.open();\n");
        s.push_str(&format!(
            "\t\tawait ui.navigateTo{}();\n",
            to_pascal_case(&flow.target_view)
        ));
        if flow.modal.is_some() {
            s.push_str(&format!(
                "\t\tawait ui.close{}Modal();\n",
                to_pascal_case(&flow.target_view)
            ));
        }
        s.push_str("\t});\n\n");
    }

    for validation in &spec.validations {
        let component = &validation.component;
        s.push_str("\ttest('form validation blocks empty submit', async ({ page }) => {\n");
        s.push_str(&format!("\t\tconst ui = new {class}(page);\n"));
        s.push_str("\t\tawait ui.open();\n");
        s.push_str(&format!(
            "\t\tawait ui.submit{}();\n",
            to_pascal_case(component)
        ));
        s.push_str(&format!(
            "\t\tawait expect(ui.{component}Input('{}')).toHaveJSProperty('validity.valid', false);\n",
            js_string(&validation.field)
        ));
        s.push_str("\t});\n\n");
    }

    for round_trip in &spec.round_trips {
        let component = &round_trip.component;
        let fill = format!(
            "fill{}{}",
            to_pascal_case(component),
            to_pascal_case(&round_trip.field)
        );
        s.push_str("\ttest('form round trip persists changes', async ({ page, request }) => {\n");
        s.push_str(&format!("\t\tconst ui = new {class}(page);\n"));
        s.push_str(&format!(
            "\t\tconst created = await (await request.post('{}', {{ data: {} }})).json();\n",
            round_trip.fixture.base_path,
            round_trip.fixture.data_literal()
        ));
        s.push_str("\t\tconst createdId = created.data?.id ?? created.id;\n");
        s.push_str(&format!(
            "\t\tawait ui.open({{ {param}: createdId }});\n",
            param = round_trip.id_param
        ));
        s.push_str(&format!(
            "\t\tawait expect(ui.{component}Input('{}')).not.toHaveValue('');\n",
            js_string(&round_trip.field)
        ));
        s.push_str(&format!(
            "\t\tawait ui.{}('{}');\n",
            fill,
            js_string(&round_trip.updated)
        ));
        s.push_str(&format!(
            "\t\tawait ui.save{}();\n",
            to_pascal_case(component)
        ));
        s.push_str(&format!(
            "\t\tconst persisted = await (await request.get(`{}/${{createdId}}`)).json();\n",
            round_trip.fixture.base_path
        ));
        s.push_str(&format!(
            "\t\texpect((persisted.data ?? persisted).{}).toBe('{}');\n",
            round_trip.field,
            js_string(&round_trip.updated)
        ));
        s.push_str("\t});\n\n");
    }

    while s.ends_with("\n\n") {
        s.pop();
    }
    s.push_str("});\n");
    s
}

/// Render a view's `{view}.workflow.spec.ts`: one test per workflow
/// component, mirroring the non-IFML workflow test's "initial state"
/// assertion. State badges and transition buttons are driven through the
/// page class (#317); the API fixture + persistence GET stay spec-side.
pub(crate) fn render_workflow_spec(vc: &IfmlViewContainer, tests: &[WorkflowTest]) -> String {
    let class = format!("{}Page", to_pascal_case(&vc.name));
    let label = vc.label.clone().unwrap_or_else(|| vc.name.clone());
    let mut s = String::new();
    s.push_str("// Generated by codegraph. DO NOT EDIT.\n");
    s.push_str(&format!(
        "// IFML Playwright E2E workflow tests for view {}.\n// State badges + transition buttons are driven through the {} page class.\n\n",
        vc.name, class
    ));
    s.push_str("import { test, expect } from '@playwright/test';\n\n");
    s.push_str(&format!(
        "import {{ {class} }} from '../pages/{}-page';\n\n",
        to_kebab_case(&vc.name)
    ));
    s.push_str(&format!(
        "test.describe('{} workflow', () => {{\n",
        js_string(&label)
    ));

    for workflow in tests {
        let component = &workflow.component_name;
        s.push_str(&format!(
            "\ttest('shows the initial workflow state for {}', async ({{ page, request }}) => {{\n",
            js_string(component)
        ));
        s.push_str(&format!("\t\tconst ui = new {class}(page);\n"));
        s.push_str(&format!(
            "\t\tconst created = await (await request.post('{}', {{ data: {} }})).json();\n",
            workflow.fixture.base_path,
            workflow.fixture.data_literal()
        ));
        open_with_fixture_id(&mut s, &workflow.id_param);
        s.push_str(&format!(
            "\t\tawait ui.expect{}State('{}');\n",
            to_pascal_case(component),
            js_string(&workflow.initial_state)
        ));
        s.push_str("\t});\n\n");

        if let Some(transition) = &workflow.transition {
            s.push_str(&format!(
                "\ttest('transitions {} from {} to {}', async ({{ page, request }}) => {{\n",
                js_string(component),
                js_string(&transition.from),
                js_string(&transition.to)
            ));
            s.push_str(&format!("\t\tconst ui = new {class}(page);\n"));
            s.push_str(&format!(
                "\t\tconst created = await (await request.post('{}', {{ data: {} }})).json();\n",
                workflow.fixture.base_path,
                workflow.fixture.data_literal()
            ));
            s.push_str("\t\tconst createdId = created.data?.id ?? created.id;\n");
            open_with_created_id(&mut s, &workflow.id_param);
            s.push_str(&format!(
                "\t\tawait ui.transition{}To('{}');\n",
                to_pascal_case(component),
                js_string(&transition.to)
            ));
            s.push_str(&format!(
                "\t\tawait ui.expect{}State('{}');\n",
                to_pascal_case(component),
                js_string(&transition.to)
            ));
            // Persistence check via the generated workflow-state endpoint
            // (`current_state` is authoritative; the entity status column is
            // the fallback for pipelines that sync it).
            s.push_str(&format!(
                "\t\tconst fetched = await (await request.get(`{}/${{createdId}}/workflow`)).json();\n",
                workflow.fixture.base_path
            ));
            s.push_str(&format!(
                "\t\texpect(fetched.data?.current_state ?? fetched.data?.status).toBe('{}');\n",
                js_string(&transition.to)
            ));
            s.push_str("\t});\n\n");
        }
    }

    while s.ends_with("\n\n") {
        s.pop();
    }
    s.push_str("});\n");
    s
}

/// The open call for a spec whose fixture id is in scope as `created`.
fn open_with_fixture_id(s: &mut String, id_param: &Option<String>) {
    match id_param {
        Some(param) => s.push_str(&format!(
            "\t\tawait ui.open({{ {param}: created.data?.id ?? created.id }});\n"
        )),
        None => s.push_str("\t\tawait ui.open();\n"),
    }
}

/// The open call for a spec whose fixture id is in scope as `createdId`.
fn open_with_created_id(s: &mut String, id_param: &Option<String>) {
    match id_param {
        Some(param) => s.push_str(&format!("\t\tawait ui.open({{ {param}: createdId }});\n")),
        None => s.push_str("\t\tawait ui.open();\n"),
    }
}

/// Render a view's `{view}.ux.spec.ts` (issue #303): ux-rules fallback
/// markup assertions computed from the SAME resolution the route generator
/// renders from. Row/chip/menu/timeline locators come from the page class's
/// `UxTable` component object (#317); the Intl formatter mirrors stay
/// in-spec (see the module comment for why).
pub(crate) fn render_ux_spec(view_name: &str, test: &UxViewTest) -> String {
    let class = format!("{}Page", to_pascal_case(view_name));
    let component = &test.component_name;
    let mut s = String::new();
    s.push_str("// Generated by codegraph. DO NOT EDIT.\n");
    s.push_str(&format!(
        "// IFML Playwright E2E ux-rules tests for view {} component {} (#303).\n// Locators come from the page class's UxTable component object (#317).\n\n",
        test.route.trim_start_matches('/'),
        component
    ));
    s.push_str("import { test, expect } from '@playwright/test';\n\n");
    s.push_str(&format!(
        "import {{ {class} }} from '../pages/{}-page';\n\n",
        to_kebab_case(view_name)
    ));
    s.push_str(&format!(
        "test.describe('{} ux', () => {{\n",
        js_string(component)
    ));
    s.push_str(&format!(
        "\tconst UX_BASE = '{}';\n",
        test.fixture.base_path
    ));
    s.push_str(&format!(
        "\tconst UX_DATA = {};\n",
        test.fixture.data_literal()
    ));
    s.push_str(&format!(
        "\tconst UX_LOCALE = '{}';\n",
        js_string(&test.locale)
    ));
    s.push_str(&format!(
        "\tconst UX_MONEY_OPTS = {};\n\n",
        test.money_options
    ));
    s.push_str(
        "\tasync function createUxRow(request: any, overrides: Record<string, unknown> = {}) {\n",
    );
    s.push_str("\t\tconst response = await request.post(UX_BASE, { data: { ...UX_DATA, ...overrides } });\n");
    s.push_str("\t\texpect(response.ok(), 'ux fixture entity should be created').toBeTruthy();\n");
    s.push_str("\t\tconst body = await response.json();\n");
    s.push_str("\t\treturn (body.data ?? body) as Record<string, unknown>;\n\t}\n");

    if !test.chip_checks.is_empty() {
        s.push_str(
            "\n\ttest('ux chips render with tone variants', async ({ page, request }) => {\n",
        );
        s.push_str(&format!("\t\tconst ui = new {class}(page);\n"));
        for (index, chip) in test.chip_checks.iter().enumerate() {
            match &chip.override_literal {
                Some(literal) => s.push_str(&format!(
                    "\t\tawait createUxRow(request, {{ 'title': 'Ux chips {index}', {}: {} }});\n",
                    js_string(&chip.field),
                    literal
                )),
                // No override: the chip's value is what create materializes
                // (the workflow initial state, via the DDL default).
                None => s.push_str(&format!(
                    "\t\tawait createUxRow(request, {{ 'title': 'Ux chips {index}' }});\n"
                )),
            }
        }
        s.push_str("\t\tawait ui.open();\n");
        for chip in &test.chip_checks {
            s.push_str(&format!(
                "\t\t{{\n\t\t\tconst chip = ui.{comp}.chipFor('{text}');\n",
                comp = component,
                text = js_string(&chip.text)
            ));
            s.push_str("\t\t\tawait expect(chip).toBeVisible();\n");
            s.push_str(&format!(
                "\t\t\tawait expect(chip).toHaveText('{}');\n",
                js_string(&chip.text)
            ));
            s.push_str(&format!(
                "\t\t\tawait expect(chip).toHaveAttribute('data-chip-variant', '{}');\n\t\t}}\n",
                js_string(&chip.variant)
            ));
        }
        s.push_str("\t});\n");
    }

    if !test.column_checks.is_empty() {
        s.push_str("\n\ttest('ux numeric columns align and format through Intl', async ({ page, request }) => {\n");
        s.push_str(&format!("\t\tconst ui = new {class}(page);\n"));
        s.push_str("\t\tawait createUxRow(request, { 'title': 'Ux formats 0' });\n");
        s.push_str("\t\tawait ui.open();\n");
        s.push_str(&format!(
            "\t\tconst row = ui.{comp}.rowFor('Ux formats 0');\n",
            comp = component
        ));
        for check in &test.column_checks {
            if let Some(header) = &check.header {
                let quoted = js_string(header);
                s.push_str("\t\t{\n");
                s.push_str(&format!(
                    "\t\t\tconst th = ui.{comp}.root().locator('thead th').filter({{ hasText: '{quoted}' }});\n",
                    comp = component
                ));
                s.push_str("\t\t\tawait expect(th).toHaveClass(/text-right/);\n\t\t}\n");
            }
            s.push_str("\t\t{\n");
            s.push_str(&format!(
                "\t\t\tconst td = row.locator('td').nth({});\n",
                check.cell_index
            ));
            match &check.format {
                UxCellFormat::Money { literal } => {
                    if check.assert_right {
                        s.push_str("\t\t\tawait expect(td).toHaveClass(/text-right/);\n");
                        s.push_str("\t\t\tawait expect(td).toHaveClass(/tabular-nums/);\n");
                    }
                    s.push_str(
                        "\t\t\tconst fmt = new Intl.NumberFormat(UX_LOCALE, UX_MONEY_OPTS);\n",
                    );
                    s.push_str(&format!(
                        "\t\t\tawait expect(td).toHaveText(fmt.format({literal}));\n"
                    ));
                }
                UxCellFormat::Quantity { literal } => {
                    if check.assert_right {
                        s.push_str("\t\t\tawait expect(td).toHaveClass(/text-right/);\n");
                        s.push_str("\t\t\tawait expect(td).toHaveClass(/tabular-nums/);\n");
                    }
                    s.push_str("\t\t\tconst fmt = new Intl.NumberFormat(UX_LOCALE);\n");
                    s.push_str(&format!(
                        "\t\t\tawait expect(td).toHaveText(fmt.format({literal}));\n"
                    ));
                }
                UxCellFormat::Date { literal } => {
                    if check.assert_right {
                        s.push_str("\t\t\tawait expect(td).toHaveClass(/text-right/);\n");
                    }
                    s.push_str("\t\t\tconst fmt = new Intl.DateTimeFormat(UX_LOCALE, { dateStyle: 'medium' });\n");
                    s.push_str(&format!(
                        "\t\t\tawait expect(td).toHaveText(fmt.format(new Date('{literal}')));\n"
                    ));
                }
            }
            s.push_str("\t\t}\n");
        }
        s.push_str("\t});\n");
    }

    if let Some(copy) = &test.copy_check {
        s.push_str(
            "\n\ttest('ux copy chips write the clipboard', async ({ page, request }) => {\n",
        );
        s.push_str(&format!("\t\tconst ui = new {class}(page);\n"));
        s.push_str("\t\tconst created = await createUxRow(request, { 'title': 'Ux copies 0' });\n");
        s.push_str("\t\tawait ui.open();\n");
        s.push_str(&format!(
            "\t\tawait ui.{comp}.copyCell(ui.{comp}.rowFor('Ux copies 0'), String(created['{field}'] ?? ''));\n",
            comp = component,
            field = js_string(&copy.field)
        ));
        s.push_str("\t});\n");
    }

    if let Some(menu) = &test.menu {
        s.push_str(
            "\n\ttest('ux row actions open the overflow menu', async ({ page, request }) => {\n",
        );
        s.push_str(&format!("\t\tconst ui = new {class}(page);\n"));
        s.push_str("\t\tawait createUxRow(request, { 'title': 'Ux menu 0' });\n");
        s.push_str("\t\tawait ui.open();\n");
        s.push_str(&format!(
            "\t\tconst menu = await ui.{comp}.openActions();\n",
            comp = component
        ));
        s.push_str("\t\tawait menu.getByRole('button').first().click();\n");
        s.push_str(&format!(
            "\t\tawait page.waitForURL(new RegExp('{}'));\n",
            js_string(&menu.target_pattern)
        ));
        s.push_str("\t});\n");
    }

    if let Some(timeline) = &test.timeline {
        s.push_str(
            "\n\ttest('ux timeline renders entries newest-first', async ({ page, request }) => {\n",
        );
        s.push_str(&format!("\t\tconst ui = new {class}(page);\n"));
        s.push_str("\t\tawait createUxRow(request, { 'title': 'Ux timeline 0' });\n");
        s.push_str("\t\tawait createUxRow(request, { 'title': 'Ux timeline 1' });\n");
        s.push_str("\t\tawait ui.open();\n");
        s.push_str(&format!(
            "\t\tconst timeline = ui.{comp}.timelineRoot();\n",
            comp = component
        ));
        s.push_str("\t\tawait expect(timeline).toBeVisible();\n");
        s.push_str(&format!(
            "\t\tconst items = ui.{comp}.timelineItems();\n",
            comp = component
        ));
        s.push_str("\t\texpect(await items.count()).toBeGreaterThan(0);\n");
        s.push_str("\t\tconst times = await items.locator('time').allTextContents();\n");
        s.push_str("\t\tfor (const text of times) {\n\t\t\texpect(text.trim().length).toBeGreaterThan(0);\n\t\t}\n");
        if let Some(literal) = &timeline.order_literal {
            s.push_str(&format!(
                "\t\t{{\n\t\t\tconst fmt = new Intl.DateTimeFormat(UX_LOCALE, {{ dateStyle: 'medium' }});\n\t\t\texpect(times).toContain(fmt.format(new Date('{literal}')));\n\t\t}}\n"
            ));
        }
        s.push_str(
            "\t\tconst parsed = times.map((t) => Date.parse(t)).filter((v) => !Number.isNaN(v));\n",
        );
        s.push_str("\t\tfor (let i = 1; i < parsed.length; i++) {\n\t\t\texpect(parsed[i]).toBeLessThanOrEqual(parsed[i - 1]);\n\t\t}\n");
        s.push_str("\t});\n");
    }

    s.push_str("});\n");
    s
}
