//! Spec rendering for the IFML e2e generator (issue #317): every spec kind
//! drives the view through the emitted POM page classes — zero raw
//! `data-testid`/`getByTestId` construction in spec bodies.
//!
//! Survivor locator usage in spec bodies (NOT testid construction):
//! - `page.addInitScript` persona seeding (per-spec, unchanged);
//! - `request.post/get` API fixtures (data setup, not UI interaction);
//! - `row.locator('td').nth(i)` cell addressing within a POM-provided row
//!   and `menu.getByRole('button')` menu-item addressing (position/role
//!   queries over POM locators);
//! - in-spec `Intl` computations in the ux spec: the IFML pages format
//!   dates `dateStyle: 'medium'` (no time part), which deliberately
//!   diverges from the kernel's `formatDateTime` mirror — the formatter
//!   semantics stay exact here instead of drifting with the kernel.

