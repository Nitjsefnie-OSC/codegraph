//! The IFML POM page-class renderer (#317): [`render_pom_page`] turns a
//! [`ViewPom`](super::pom::ViewPom) plan into the
//! `tests/pages/{view-kebab}-page.ts` TypeScript.

use codegraph_naming::to_pascal_case;

use super::fixtures::js_string;
use super::pom::{PomFieldKind, PomWorkflowMethods, ViewPom};

// Fail fast: a server-side deny redirect is near-instant; five seconds is generous.
const DENIAL_REDIRECT_TIMEOUT_MS: u32 = 5_000;

// ── Page-class rendering ─────────────────────────────────────────────────────

/// The `tests/pages/{view-kebab}-page.ts` content for one view.
pub(super) fn render_pom_page(pom: &ViewPom) -> String {
    let denial_presentation = pom.auth_enabled
        && pom.denial_target.is_some()
        && (pom.heading.is_some() || pom.primary_root.is_some());
    let needs_expect = pom.collections.iter().any(|c| c.workflow.is_some())
        || pom.forms.iter().any(|f| f.workflow.is_some())
        || pom.details.iter().any(|d| d.workflow.is_some())
        || pom.flows.iter().any(|f| f.close_method.is_some())
        || denial_presentation;
    let needs_ux_table = pom.collections.iter().any(|c| c.ux_table.is_some());

    let mut s = String::new();
    s.push_str("// Generated by codegraph. DO NOT EDIT.\n");
    s.push_str(&format!(
        "//\n// Playwright Object Model page class for view {} (issue #317).\n\
         // All selector/testid construction lives here; the IFML specs drive\n\
         // the view through this class — zero raw testids in spec bodies.\n\n",
        pom.view_name
    ));
    if needs_expect {
        s.push_str("import { expect, type Locator, type Page } from '@playwright/test';\n\n");
    } else {
        s.push_str("import { type Locator, type Page } from '@playwright/test';\n\n");
    }
    if needs_ux_table {
        s.push_str("import { BasePage } from './support/base-page';\n");
        s.push_str("import { UxTable } from './support/ux-table';\n\n");
    } else {
        s.push_str("import { BasePage } from './support/base-page';\n\n");
    }

    s.push_str(&format!(
        "export class {} extends BasePage {{\n",
        pom.class_name
    ));
    s.push_str(&format!("  static readonly route = '{}';\n\n", pom.route));
    s.push_str("  /** Route + query string (SvelteKit views resolve params from the URL). */\n");
    s.push_str("  url(params: Record<string, string> = {}): string {\n");
    s.push_str("    const search = Object.entries(params)\n");
    s.push_str("      .map(([key, value]) => `${key}=${encodeURIComponent(value)}`)\n");
    s.push_str("      .join('&');\n");
    s.push_str(&format!(
        "    return search ? `{}?${{search}}` : '{}';\n  }}\n\n",
        pom.route, pom.route
    ));
    s.push_str("  /** Navigate to the view route with bound params. */\n");
    s.push_str("  async open(params: Record<string, string> = {}): Promise<void> {\n");
    s.push_str("    await this.page.goto(this.url(params));\n");
    s.push_str("  }\n\n");

    // Structure surface.
    if let Some(label) = &pom.heading {
        s.push_str("  heading(): Locator {\n");
        s.push_str(&format!(
            "    return this.page.getByRole('heading', {{ name: '{}' }});\n  }}\n\n",
            js_string(label)
        ));
    }
    if let Some(primary) = &pom.primary_root {
        s.push_str("  /** Primary component root (the render assertion target). */\n");
        s.push_str("  primaryRoot(): Locator {\n");
        s.push_str(&format!(
            "    return this.page.getByTestId('{}');\n  }}\n\n",
            primary
        ));
    }
    if let Some(nav) = &pom.nav_testid {
        s.push_str("  /** Landmark shell nav (mapped `shell` component). */\n");
        s.push_str("  navRoot(): Locator {\n");
        s.push_str(&format!(
            "    return this.page.getByTestId('{}');\n  }}\n\n",
            nav
        ));
    }
    if let Some(container) = &pom.container_testid {
        s.push_str("  /** Presentation-container wrapper (xor view grouping). */\n");
        s.push_str("  containerRoot(): Locator {\n");
        s.push_str(&format!(
            "    return this.page.getByTestId('{}');\n  }}\n\n",
            container
        ));
    }
    if let Some(denial) = &pom.denial_target {
        s.push_str(&format!(
            "  /** Denied personas redirect within {DENIAL_REDIRECT_TIMEOUT_MS} ms to fail fast: a server-side deny redirect is near-instant. */\n"
        ));
        s.push_str("  async expectDenied(): Promise<void> {\n");
        s.push_str(&format!(
            "    await this.page.waitForURL('{}', {{ timeout: {DENIAL_REDIRECT_TIMEOUT_MS} }});\n  }}\n\n",
            js_string(denial)
        ));
    }
    if denial_presentation {
        s.push_str("  /** The guarded surface must stay hidden from denied personas\n   * (issue #468 W5): neither the heading nor the primary root shows. */\n");
        s.push_str("  async expectDeniedPresentation(reason: string): Promise<void> {\n");
        if pom.heading.is_some() {
            s.push_str("    await expect(this.heading(), reason).not.toBeVisible();\n");
        }
        if pom.primary_root.is_some() {
            s.push_str("    await expect(this.primaryRoot(), reason).not.toBeVisible();\n");
        }
        s.push_str("  }\n\n");
    }
    if !pom.steps.is_empty() {
        s.push_str("  /** Wizard steps (xor containers, issue #468 W5): the step's\n   * presentation surface, by container name. */\n");
        s.push_str("  step(name: string): Locator {\n");
        s.push_str("    const steps: Record<string, string> = {\n");
        for step in &pom.steps {
            s.push_str(&format!(
                "      '{}': '{}',\n",
                js_string(&step.name),
                js_string(&step.testid)
            ));
        }
        s.push_str("    };\n");
        s.push_str("    const testid = steps[name];\n");
        s.push_str("    if (!testid) {\n");
        s.push_str("      throw new Error(`unknown wizard step '${name}'`);\n");
        s.push_str("    }\n");
        s.push_str("    return this.page.getByTestId(testid);\n  }\n\n");
    }

    // Collections.
    for collection in &pom.collections {
        s.push_str(&format!("  // ── Collection: {} ──\n\n", collection.name));
        if let Some(ux) = &collection.ux_table {
            s.push_str("  /** ux-rules plan surface: the shared kernel contract\n   * (chips/sort/menu/copy/timeline per the entity's plan). */\n");
            s.push_str(&format!(
                "  readonly {} = new UxTable(this.page, {{\n",
                collection.name
            ));
            s.push_str(&format!("    module: '{}',\n", collection.name));
            s.push_str(&format!("    locale: '{}',\n", js_string(&ux.locale)));
            if let Some(currency) = &ux.currency {
                s.push_str(&format!("    currency: '{}',\n", js_string(currency)));
            }
            s.push_str("  });\n\n");
        }
        if !collection.row_testid.is_empty() {
            s.push_str("  /** First body row — the row-click navigation target. */\n");
            s.push_str(&format!("  {}Row(): Locator {{\n", collection.name));
            s.push_str(&format!(
                "    return this.page.getByTestId('{}').first();\n  }}\n\n",
                collection.row_testid
            ));
        }
        if pom.auth_enabled && collection.ux_table.is_some() {
            s.push_str(
                "  /** Delete a row (first by default) through the overflow menu\n   * and its confirmation dialog. */\n",
            );
            s.push_str(&format!(
                "  async {}DeleteViaMenu(row?: Locator): Promise<void> {{\n",
                collection.name
            ));
            s.push_str(&format!(
                "    await this.{}.deleteViaMenu(row);\n  }}\n\n",
                collection.name
            ));
        }
        s.push_str(&render_workflow_section(
            &collection.name,
            &collection.pascal,
            collection.workflow.as_ref(),
        ));
    }

    // Forms.
    for form in &pom.forms {
        s.push_str(&format!("  // ── Form: {} ──\n\n", form.name));
        s.push_str(&format!("  {}Form(): Locator {{\n", form.name));
        s.push_str(&format!(
            "    return this.page.getByTestId('{}');\n  }}\n\n",
            form.form_testid
        ));
        s.push_str("  /** A form input by field name (the `name=` convention). */\n");
        s.push_str(&format!(
            "  {}Input(field: string): Locator {{\n",
            form.name
        ));
        s.push_str(&format!(
            "    return this.{}Form().locator(`[name=\"${{field}}\"]`);\n  }}\n\n",
            form.name
        ));
        s.push_str(&format!("  {}Submit(): Locator {{\n", form.name));
        s.push_str(&format!(
            "    return this.page.getByTestId('{}');\n  }}\n\n",
            form.submit_testid
        ));
        for field in &form.fields {
            let fill_method = format!("fill{}{}", form.pascal, to_pascal_case(&field.name));
            s.push_str(&format!(
                "  async {}(value: string): Promise<void> {{\n",
                fill_method
            ));
            match field.kind {
                PomFieldKind::Select => s.push_str(&format!(
                    "    await this.{}Input('{}').selectOption(value);\n  }}\n\n",
                    form.name, field.name
                )),
                PomFieldKind::Radio => s.push_str(&format!(
                    "    await this.{}Form().locator(`[name=\"{}\"][value=\"${{value}}\"]`).check();\n  }}\n\n",
                    form.name, field.name
                )),
                PomFieldKind::Checkbox => s.push_str(&format!(
                    "    await this.{}Input('{}').setChecked(value === 'true');\n  }}\n\n",
                    form.name, field.name
                )),
                PomFieldKind::DatetimeLocal => {
                    s.push_str("    // Datetime inputs take the local (Z-stripped) form.\n");
                    s.push_str(&format!(
                        "    await this.{}Input('{}').fill(value.replace(/:\\d{{2}}Z$/, ''));\n  }}\n\n",
                        form.name, field.name
                    ));
                }
                PomFieldKind::Textarea | PomFieldKind::Text => s.push_str(&format!(
                    "    await this.{}Input('{}').fill(value);\n  }}\n\n",
                    form.name, field.name
                )),
            }
        }
        s.push_str("  /** Click the form's submit control. */\n");
        s.push_str(&format!(
            "  async submit{}(): Promise<void> {{\n",
            form.pascal
        ));
        s.push_str(&format!(
            "    await this.{}Submit().click();\n  }}\n\n",
            form.name
        ));
        if let Some(pattern) = &form.save_pattern {
            s.push_str("  /** Submit and wait for the save navigation. */\n");
            s.push_str(&format!(
                "  async save{}(): Promise<void> {{\n",
                form.pascal
            ));
            s.push_str(&format!("    await this.{}Submit().click();\n", form.name));
            s.push_str(&format!(
                "    await this.page.waitForURL(new RegExp('{}'));\n  }}\n\n",
                js_string(pattern)
            ));
        }
        if let (true, Some(cancel)) = (pom.auth_enabled, &form.cancel) {
            s.push_str("  /** The form's cancel control. */\n");
            s.push_str(&format!("  {}Cancel(): Locator {{\n", form.name));
            s.push_str(&format!(
                "    return this.page.getByTestId('{}');\n  }}\n\n",
                cancel.testid
            ));
            s.push_str("  /** Click cancel and wait for the cancel navigation. */\n");
            s.push_str(&format!(
                "  async press{}Cancel(): Promise<void> {{\n",
                form.pascal
            ));
            s.push_str(&format!("    await this.{}Cancel().click();\n", form.name));
            s.push_str(&format!(
                "    await this.page.waitForURL(new RegExp('{}'));\n  }}\n\n",
                js_string(&cancel.pattern)
            ));
        }
        s.push_str(&render_workflow_section(
            &form.name,
            &form.pascal,
            form.workflow.as_ref(),
        ));
    }

    // Details.
    for details in &pom.details {
        s.push_str(&format!("  // ── Details: {} ──\n\n", details.name));
        s.push_str(&format!("  {}Details(): Locator {{\n", details.name));
        s.push_str(&format!(
            "    return this.page.getByTestId('{}');\n  }}\n\n",
            details.root_testid
        ));
        for (index, field) in details.fields.iter().enumerate() {
            s.push_str(&format!(
                "  /** The `{}` value slot (`dd` position {}). */\n",
                field, index
            ));
            s.push_str(&format!(
                "  {}{}(): Locator {{\n",
                details.name,
                to_pascal_case(field)
            ));
            s.push_str(&format!(
                "    return this.{}Details().locator('dd').nth({});\n  }}\n\n",
                details.name, index
            ));
        }
        s.push_str(&render_workflow_section(
            &details.name,
            &to_pascal_case(&details.name),
            details.workflow.as_ref(),
        ));
    }

    // Flows.
    for flow in &pom.flows {
        s.push_str("  /** Row-click navigation flow — the same control the markup\n   * wires to the event handler. */\n");
        s.push_str(&format!("  async {}(): Promise<void> {{\n", flow.method));
        s.push_str(&format!(
            "    await this.page.getByTestId('{}').first().click();\n",
            flow.row_testid
        ));
        s.push_str(&format!(
            "    await this.page.waitForURL(new RegExp('{}'));\n  }}\n\n",
            js_string(&flow.pattern)
        ));
        if let (Some(method), Some(wrapper), Some(close), Some(back)) = (
            &flow.close_method,
            &flow.close_wrapper_testid,
            &flow.close_testid,
            &flow.back_pattern,
        ) {
            s.push_str("  /** Close the modal opened by the flow: wrapper visible,\n   * close click, back-navigation wait. */\n");
            s.push_str(&format!("  async {}(): Promise<void> {{\n", method));
            s.push_str(&format!(
                "    await expect(this.page.getByTestId('{}')).toBeVisible();\n",
                wrapper
            ));
            s.push_str(&format!(
                "    await this.page.getByTestId('{}').click();\n",
                close
            ));
            s.push_str(&format!(
                "    await this.page.waitForURL(new RegExp('{}'));\n  }}\n\n",
                js_string(back)
            ));
        }
    }

    // Journey hop methods (issue #468 W5): the controls the
    // `{view}.journey.spec.ts` walks drive, composed from the same
    // accessors the specs use.
    for step in &pom.journey_steps {
        s.push_str("  /** Journey hop (issue #468 W5): the control the IFML event binds\n   * to, then the landing route. */\n");
        s.push_str(&format!("  async {}(): Promise<void> {{\n", step.method));
        for (fill, literal) in &step.fills {
            s.push_str(&format!("    await this.{}({});\n", fill, literal));
        }
        if step.row {
            s.push_str(&format!(
                "    await this.{}Row().click();\n",
                step.component
            ));
        }
        if step.submit {
            s.push_str(&format!(
                "    await this.{}Submit().click();\n",
                step.component
            ));
        }
        s.push_str(&format!(
            "    await this.page.waitForURL(new RegExp('{}'));\n  }}\n\n",
            js_string(&step.pattern)
        ));
    }

    while s.ends_with("\n\n") {
        s.pop();
    }
    s.push_str("}\n");
    s
}

/// The shared workflow surface for one component: state badge accessor,
/// `expect{Component}State` (`.first()`-scoped for collections — badges
/// render per row there), and the transition map matching the rendered
/// buttons exactly.
pub(super) fn render_workflow_section(
    component: &str,
    pascal: &str,
    workflow: Option<&PomWorkflowMethods>,
) -> String {
    let Some(workflow) = workflow else {
        return String::new();
    };
    let mut s = String::new();
    s.push_str(&format!("  {component}StateBadge(): Locator {{\n"));
    s.push_str(&format!(
        "    return this.page.getByTestId('{component}-state');\n  }}\n\n"
    ));
    let first = if workflow.is_collection {
        ".first()"
    } else {
        ""
    };
    s.push_str(&format!(
        "  async expect{pascal}State(state: string): Promise<void> {{\n"
    ));
    s.push_str(&format!(
        "    await expect(this.{component}StateBadge(){first}).toContainText(state);\n  }}\n\n"
    ));
    if !workflow.transitions.is_empty() {
        s.push_str("  /** Click the transition button for `to` (rendered when the\n   * workflow generates action endpoints). */\n");
        s.push_str(&format!(
            "  async transition{pascal}To(to: string): Promise<void> {{\n"
        ));
        s.push_str("    const buttons: Record<string, string> = {\n");
        for (state, testid) in &workflow.transitions {
            s.push_str(&format!("      '{}': '{}',\n", js_string(state), testid));
        }
        s.push_str("    };\n");
        s.push_str("    const testid = buttons[to];\n");
        s.push_str("    if (!testid) {\n");
        s.push_str("      throw new Error(`no transition button to '${to}'`);\n");
        s.push_str("    }\n");
        s.push_str("    await this.page.getByTestId(testid).click();\n");
        s.push_str("  }\n\n");
    }
    s
}
