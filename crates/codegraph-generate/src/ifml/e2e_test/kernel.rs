pub(crate) const UX_TABLE_TS: &str = r#"// Generated by codegraph. DO NOT EDIT.
//
// Shared Playwright Object Model kernel — UxTable (issue #317, IFML half).
// The method surface mirrors the entity kernel's UxTable
// (templates/ui/test/_pom_kernel.tera) EXACTLY: same names, same
// ids::-mirrored testid fragments, same Intl mirrors. Selector knowledge
// lives here, never in the spec bodies.

import { expect, type Locator, type Page } from '@playwright/test';

export interface UxTableConfig {
  /** Testid prefix family — the IFML component name. */
  module: string;
  /** BCP-47 locale mirror for the Intl assertions (ux-rules `[format]`). */
  locale: string;
  /** ISO 4217 currency mirror (money columns). */
  currency?: string;
}

const EM_DASH = '\u2014';

/** The shared ux contract component object. `rows`/`rowFor`/`chipFor`/
 * `sortBy`/`openActions`/`deleteViaMenu`/`copyCell`/`timelineItems`/
 * `expectFormatted`/`expectRightAligned`/`expectZebra`/`expectInactive`
 * over the ids::-mirrored literals. Assertions that need the Intl mirror
 * run the SAME formatters the page does, from the configured locale and
 * currency. */
export class UxTable {
  constructor(
    private readonly page: Page,
    private readonly cfg: UxTableConfig,
  ) {}

  private tid(suffix: string): string {
    return `[data-testid="${this.cfg.module}-${suffix}"]`;
  }

  /** `{module}-table` — the list table root. */
  root(): Locator {
    return this.page.locator(this.tid('table'));
  }

  /** Body rows of the table. */
  rows(): Locator {
    return this.page.locator('tbody tr');
  }

  /** First body row whose text contains `text`. */
  rowFor(text: string): Locator {
    return this.rows().filter({ hasText: text }).first();
  }

  /** `tbody tr:first-child td:nth-child(tdIndex)` (1-based data column). */
  cell(tdIndex: number): Locator {
    return this.page.locator(`tbody tr:first-child td:nth-child(${tdIndex})`);
  }

  /** The first body row's first cell (the readable-lead slot). */
  firstCell(): Locator {
    return this.page.locator('tbody tr:first-child td:first-child');
  }

  async headerCount(): Promise<number> {
    return this.page.locator('thead th').count();
  }

  /** `{module}-chip` filtered to the exact fixture label. */
  chipFor(text: string): Locator {
    return this.page.locator(this.tid('chip')).filter({ hasText: text }).first();
  }

  /** `{module}-sort-{field}` — a column header's sort button. */
  sortButton(field: string): Locator {
    return this.page.locator(this.tid(`sort-${field}`));
  }

  /** The `th` hosting a column's sort button (its aria-sort hook). */
  sortHeader(field: string): Locator {
    return this.page.locator('thead th').filter({ has: this.sortButton(field) });
  }

  /** Click `{module}-sort-{field}` until its th reaches `dir`. */
  async sortBy(field: string, dir: 'asc' | 'desc'): Promise<void> {
    const current = (await this.sortHeader(field).getAttribute('aria-sort')) ?? 'none';
    const cycle = ['none', 'ascending', 'descending'];
    const target = dir === 'asc' ? 'ascending' : 'descending';
    let clicks = cycle.indexOf(target) - cycle.indexOf(current);
    while (clicks-- > 0) {
      await this.sortButton(field).click();
    }
  }

  /** Row-actions trigger (`{module}-actions`); first row by default. */
  actionsTrigger(row?: Locator): Locator {
    const scope = row ?? this.rows().first();
    return scope.locator(this.tid('actions')).first();
  }

  /** Open the overflow menu for a row and return it once visible. */
  async openActions(row?: Locator): Promise<Locator> {
    await this.actionsTrigger(row).click();
    const menu = this.menu();
    await expect(menu).toBeVisible();
    return menu;
  }

  /** `{module}-actions-menu` — the overflow menu. The fallback markup
   * renders one menu PER ROW; callers operate on the row `openActions`
   * opened (the first row by default), so first-match is the contract. */
  menu(): Locator {
    return this.page.locator(this.tid('actions-menu')).first();
  }

  /** The menu's Delete item (`{module}-action-delete`), first row. */
  menuDelete(): Locator {
    return this.page.locator(this.tid('action-delete')).first();
  }

  /** The row-delete dialog (`{module}-delete-dialog`, issue #468). */
  deleteConfirm(): Locator {
    return this.page.locator(this.tid('delete-dialog'));
  }

  /** Its confirm button (`{module}-delete-dialog-confirm`). */
  deleteConfirmConfirm(): Locator {
    return this.page.locator(this.tid('delete-dialog-confirm'));
  }

  /** Menu-driven delete through the confirmation dialog. */
  async deleteViaMenu(row?: Locator): Promise<void> {
    await this.openActions(row);
    await this.menuDelete().click();
    const confirm = this.deleteConfirm();
    await expect(confirm).toBeVisible();
    await this.deleteConfirmConfirm().click();
  }

  /** The copy-chip trigger on a row (`{module}-copy`). */
  copyTrigger(row: Locator): Locator {
    return row.locator(this.tid('copy')).first();
  }

  /** Click the trigger and poll the clipboard until it carries `expected`. */
  async copyCell(row: Locator, expected: string): Promise<void> {
    await this.page.context().grantPermissions(['clipboard-read', 'clipboard-write']);
    await this.copyTrigger(row).click();
    await expect
      .poll(() => this.page.evaluate(() => navigator.clipboard.readText()))
      .toBe(expected);
  }

  /** Tooltip content locator surfacing the FULL (truncated) value. */
  tooltipFor(text: string): Locator {
    return this.page.locator('[data-slot="tooltip-content"]').filter({ hasText: text });
  }

  /** `{module}-timeline` root. */
  timelineRoot(): Locator {
    return this.page.locator(this.tid('timeline'));
  }

  /** `{module}-timeline-item` entries. */
  timelineItems(): Locator {
    return this.page.locator(this.tid('timeline-item'));
  }

  /** Every entry's `<time>` text (the DESC-order input). */
  async timelineTimes(): Promise<string[]> {
    return this.timelineItems().locator('time').allTextContents();
  }

  // ── Intl mirrors (locale/currency from the ux plan's [format]) ──────

  formatDate(value: string | number | Date): string {
    return new Intl.DateTimeFormat(this.cfg.locale, { dateStyle: 'medium' }).format(
      new Date(value as string),
    );
  }

  formatDateTime(value: string | number | Date): string {
    return new Intl.DateTimeFormat(this.cfg.locale, {
      dateStyle: 'medium',
      timeStyle: 'short',
    }).format(new Date(value as string));
  }

  formatMoney(value: number): string {
    const fmt = new Intl.NumberFormat(
      this.cfg.locale,
      this.cfg.currency ? { style: 'currency', currency: this.cfg.currency } : undefined,
    );
    return fmt.format(value);
  }

  formatQuantity(value: number): string {
    return new Intl.NumberFormat(this.cfg.locale).format(value);
  }

  // ── ux contract assertions ──────────────────────────────────────────

  /** Right-aligned column: td (and, when sortable, the th) carry
   * `text-right tabular-nums`. */
  async expectRightAligned(tdIndex: number, sortKey?: string): Promise<void> {
    const td = this.cell(tdIndex);
    await expect(td).toHaveClass(/text-right/);
    await expect(td).toHaveClass(/tabular-nums/);
    if (sortKey) {
      const th = this.sortHeader(sortKey);
      await expect(th).toHaveClass(/text-right/);
      await expect(th).toHaveClass(/tabular-nums/);
    }
  }

  /** The cell text equals the SAME Intl output the page computes for the
   * fixture value. The em-dash placeholder (a null cell on the fixture
   * row — the column is not fixture-controlled) is skipped, not failed. */
  async expectFormatted(
    tdIndex: number,
    kind: 'money' | 'quantity' | 'time-point',
    value: number | string,
  ): Promise<void> {
    const td = this.cell(tdIndex);
    if (((await td.textContent()) ?? '').trim() === EM_DASH) {
      return;
    }
    const expected =
      kind === 'money'
        ? this.formatMoney(value as number)
        : kind === 'quantity'
          ? this.formatQuantity(value as number)
          : this.formatDateTime(value as string);
    await expect(td).toHaveText(expected);
  }

  /** Zebra + hover/focus contract over the first two visual rows. */
  async expectZebra(): Promise<void> {
    const firstRow = this.rows().first();
    await expect(firstRow).toHaveClass(/hover:bg-muted\/50/);
    await expect(firstRow).toHaveClass(/focus-visible:ring-2/);
    await expect(this.rows().nth(1)).toHaveClass(/bg-muted\/50/);
  }

  /** A row carries the inactive shading marker (terminal workflow state
   * or soft-deleted). */
  async expectInactive(row: Locator): Promise<void> {
    await expect(row).toHaveAttribute('data-inactive', /.+/);
  }
}
"#;

#[cfg(test)]
mod tests {
    use super::*;

    /// Public method names declared inside a kernel TS class body: lines at
    /// two-space indent shaped `name(` / `async name(`, skipping
    /// constructors and visibility/keyword-prefixed members.
    fn method_surface(class_body: &str) -> Vec<String> {
        let keywords = [
            "if",
            "for",
            "while",
            "switch",
            "catch",
            "const",
            "let",
            "return",
            "await",
            "constructor",
            "private",
            "public",
            "readonly",
            "export",
            "interface",
            "new",
        ];
        let mut out = Vec::new();
        for line in class_body.lines() {
            let Some(rest) = line.strip_prefix("  ") else {
                continue;
            };
            if rest.starts_with(' ') || rest.is_empty() {
                continue;
            }
            let mut name = rest.trim();
            if let Some(stripped) = name.strip_prefix("async ") {
                name = stripped.trim_start();
            }
            let name = name.split('(').next().unwrap_or("").trim();
            if name.is_empty() || keywords.contains(&name) {
                continue;
            }
            if !rest
                .split('(')
                .next()
                .unwrap_or("")
                .trim_end()
                .ends_with(name)
            {
                continue;
            }
            out.push(name.to_string());
        }
        out
    }

    /// Kernel parity with the entity POM (#316): the IFML `UxTable` and
    /// `BasePage` declare the SAME public method surface as the entity
    /// kernel template renders, and carry the same `ids::` testid fragment
    /// contract. See the module comment for why the IFML kernel is
    /// Rust-built instead of rendered from the shared template.
    #[test]
    fn pom_kernel_surface_matches_entity_kernel() {
        let tera = crate::template_engine::create_tera_with_overrides(&[]).unwrap();
        let entity = crate::render_template_with_project(
            &tera,
            "ui/test/_pom_kernel.tera",
            &serde_json::json!({}),
            &crate::ProjectConfig::default(),
        )
        .unwrap();

        let entity_base = entity
            .split("export class BasePage")
            .nth(1)
            .and_then(|b| b.split("export interface UxTableConfig").next())
            .unwrap();
        let entity_ux = entity
            .split("export class UxTable")
            .nth(1)
            .expect("entity kernel carries UxTable");
        let ifml_base = BASE_PAGE_TS.split("export class BasePage").nth(1).unwrap();
        let ifml_ux = UX_TABLE_TS.split("export class UxTable").nth(1).unwrap();

        let entity_methods = method_surface(entity_ux);
        assert!(!entity_methods.is_empty(), "surface extraction is broken");
        let ifml_methods = method_surface(ifml_ux);
        for method in &entity_methods {
            assert!(
                ifml_methods.contains(method),
                "IFML UxTable is missing `{method}` from the entity kernel surface"
            );
        }
        let entity_base_methods = method_surface(entity_base);
        let ifml_base_methods = method_surface(ifml_base);
        for method in &entity_base_methods {
            assert!(
                ifml_base_methods.contains(method),
                "IFML BasePage is missing `{method}` from the entity kernel surface"
            );
        }

        // The ids:: testid fragment contract (shared fragments only — the
        // entity family is entity-pipeline-specific).
        for suffix in [
            "chip",
            "actions",
            "actions-menu",
            "copy",
            "timeline",
            "timeline-item",
        ] {
            assert!(
                ifml_ux.contains(&format!("tid('{suffix}')")),
                "IFML UxTable must mirror the `{suffix}` fragment"
            );
        }
    }
}
