/// Rust keywords that cannot be used as enum variant identifiers.
const RUST_KEYWORDS: &[&str] = &[
    "Self", "self", "super", "crate", "as", "break", "const", "continue", "else", "enum", "extern",
    "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub",
    "ref", "return", "static", "struct", "trait", "true", "type", "unsafe", "use", "where",
    "while", "async", "await", "dyn", "abstract", "become", "box", "do", "final", "macro",
    "override", "priv", "typeof", "unsized", "virtual", "yield", "try",
];

/// Template context for a codelist Rust enum.
#[derive(Debug, Serialize)]
pub struct RustEnumContext {
    pub enum_name: String,
    pub description: String,
    pub variants: Vec<RustEnumVariant>,
}

/// A single variant in a codelist Rust enum.
#[derive(Debug, Serialize)]
pub struct RustEnumVariant {
    pub name: String,
    pub code: String,
    pub serde_rename: Option<String>,
}

/// Sanitize a codelist value into a valid Rust enum variant name.
///
/// Rules (matching legacy `codelist_enum_emitter.rs`):
/// 1. Replace `+` with `Plus`, Unicode minus (`−`) with `Minus`
/// 2. Replace hyphens, spaces, dots, slashes with underscores
/// 3. Remove colons
/// 4. Convert to PascalCase
/// 5. If the result starts with a digit, prefix with `_`
/// 6. If the result is a Rust keyword, prefix with `R`
pub fn sanitize_variant_name(value: &str) -> String {
    let s = value
        .replace('+', "Plus")
        .replace('\u{2212}', "Minus") // Unicode minus sign
        .replace('-', "_")
        .replace(':', "")
        .replace([' ', '.', '/'], "_");
    let s = s.to_upper_camel_case();
    if s.starts_with(|c: char| c.is_ascii_digit()) {
        format!("_{}", s)
    } else if s.is_empty() {
        "_Empty".to_string()
    } else if RUST_KEYWORDS.contains(&s.as_str()) {
        format!("R{}", s)
    } else {
        s
    }
}

/// Generator that emits Rust enum files for all codelists in the graph,
/// plus a `mod.rs` re-exporting them.
pub struct RustCodelistGenerator {
    output_dir: PathBuf,
}

impl RustCodelistGenerator {
    pub fn new(output_dir: &Path) -> Self {
        Self {
            output_dir: output_dir.to_path_buf(),
        }
    }

    /// Generate Rust enum files for all codelists + a `mod.rs`.
    pub async fn generate_all(
        &self,
        db: &dyn GraphQuerier,
        tera: &tera::Tera,
        project: &ProjectConfig,
    ) -> Result<Vec<GeneratedFile>> {
        let codelists = db.list_codelists().await?;
        let codelist_dir = self.output_dir.join("src").join("codelist");
        if codelists.is_empty() {
            // The main lib.rs declares `pub mod codelist;` unconditionally —
            // emit an empty module so projects without codelists compile.
            return Ok(vec![GeneratedFile {
                path: codelist_dir.join("mod.rs"),
                content: "//! Codelist enum re-exports.\n\
                          //! Generated by codegraph. DO NOT EDIT.\n\
                          \n"
                .to_string(),
            }]);
        }

        // Remove stale .rs files from previous runs so leftover files
        // don't accumulate when the codelist set changes between generations.
        if codelist_dir.is_dir()
            && let Ok(entries) = std::fs::read_dir(&codelist_dir)
        {
            for entry in entries.flatten() {
                let path = entry.path();
                if path.extension().is_some_and(|e| e == "rs")
                    && path.file_name().is_some_and(|n| n != "mod.rs")
                {
                    let _ = std::fs::remove_file(&path);
                }
            }
        }

        let mut files = Vec::new();
        let mut mod_entries: Vec<(String, String)> = Vec::new(); // (snake_name, EnumName)

        for cl in &codelists {
            let enum_values = db.get_enum_values(&cl.name).await.unwrap_or_default();

            let enum_name = cl.name.clone();
            let snake_name = to_snake_case(&enum_name);
            let default_desc = format!("{} codelist values.", enum_name);
            let description = cl.description.as_deref().unwrap_or(&default_desc);

            let content = if enum_values.is_empty() {
                // Emit a 0-variant enum stub with manual Display/FromStr/Default
                // impls so DTO code referencing this codelist compiles.
                let ctx = RustEnumContext {
                    enum_name: enum_name.clone(),
                    description: description.to_string(),
                    variants: vec![],
                };
                render_template_with_project(tera, "codelist/empty_enum.tera", &ctx, project)?
            } else {
                let variants: Vec<RustEnumVariant> = enum_values
                    .iter()
                    .map(|v| {
                        let sanitized = sanitize_variant_name(&v.value);
                        let serde_rename = if sanitized != v.value {
                            Some(v.value.clone())
                        } else {
                            None
                        };
                        RustEnumVariant {
                            name: sanitized,
                            code: v.value.clone(),
                            serde_rename,
                        }
                    })
                    .collect();

                let ctx = RustEnumContext {
                    enum_name: enum_name.clone(),
                    description: description.to_string(),
                    variants,
                };
                render_template_with_project(tera, "codelist/enum.tera", &ctx, project)?
            };

            files.push(GeneratedFile {
                path: codelist_dir.join(format!("{}.rs", snake_name)),
                content,
            });

            mod_entries.push((snake_name, enum_name));
        }

        // Generate mod.rs with pub mod + pub use for each codelist enum
        if !mod_entries.is_empty() {
            mod_entries.sort_by(|a, b| a.0.cmp(&b.0));

            let mut mod_content = String::from(&format!(
                "//! Codelist enum re-exports.\n//! Generated by {} . DO NOT EDIT.\n\n",
                project.identity.generator_name
            ));
            for (snake, enum_name) in &mod_entries {
                mod_content.push_str(&format!("pub mod {};\n", snake));
                mod_content.push_str(&format!("pub use {}::{};\n\n", snake, enum_name));
            }

            files.push(GeneratedFile {
                path: codelist_dir.join("mod.rs"),
                content: mod_content,
            });
        }

        Ok(files)
    }

    /// Generate a `mod.rs` that re-exports only the codelist enums actually
    /// referenced by the generated app code (scanned from `src/domain/` and
    /// `src/api/`).  Also removes any leftover local codelist `.rs` files
    /// from previous runs — the generated app uses re-exports from
    /// `hr_domain_types`, not local copies.
    ///
    /// Root-anchored variant: scans the output root and keeps the original
    /// early-return behaviour so monolith output stays byte-identical.
    pub async fn generate_reexport_mod(
        &self,
        db: &dyn GraphQuerier,
        project: &ProjectConfig,
    ) -> Result<Vec<GeneratedFile>> {
        let codelists = db.list_codelists().await?;
        let codelist_dir = self.output_dir.join("src").join("codelist");

        // Remove leftover local codelist .rs files (not mod.rs) so
        // generate_mod_files doesn't pick them up later.
        if codelist_dir.is_dir()
            && let Ok(entries) = std::fs::read_dir(&codelist_dir)
        {
            for entry in entries.flatten() {
                let path = entry.path();
                if path.extension().is_some_and(|e| e == "rs")
                    && path.file_name().is_some_and(|n| n != "mod.rs")
                {
                    let _ = std::fs::remove_file(&path);
                }
            }
        }

        if codelists.is_empty() {
            // The main lib.rs declares `pub mod codelist;` unconditionally —
            // emit an empty module so projects without codelists compile.
            return Ok(vec![GeneratedFile {
                path: codelist_dir.join("mod.rs"),
                content: "//! Codelist enum re-exports.\n\
                          //! Generated by codegraph. DO NOT EDIT.\n\
                          \n"
                .to_string(),
            }]);
        }

        // Root (monolith) crate: re-export EVERY available codelist — not a
        // referenced-only subset. `pub use` re-exports are the crate's
        // public API (no unused-import noise), and a full list keeps
        // `src/codelist/mod.rs` identical whether or not the model carries
        // `.evt` event contracts: the events plane references codelists
        // from `src/events/contracts.rs`, and a referenced-only scan would
        // make this file flag-dependent (breaking the no-.evt byte-identity
        // contract). Sorted for deterministic output.
        let mut names: Vec<&String> = codelists.iter().map(|cl| &cl.name).collect();
        names.sort();
        let mut content = format!(
            "//! Codelist enum re-exports from {}.\n//! Generated by {} . DO NOT EDIT.\n\n",
            project.identity.domain_types_crate, project.identity.generator_name
        );
        for name in &names {
            content.push_str(&format!(
                "pub use {}::codelist::{};\n",
                project.identity.domain_types_crate, name
            ));
        }

        Ok(vec![GeneratedFile {
            path: codelist_dir.join("mod.rs"),
            content,
        }])
    }

    /// Generate a `mod.rs` re-exporting only the codelist enums referenced by
    /// the Rust source under `base/src/domain/` and `base/src/api/`.
    ///
    /// In workers topology this runs per domain worker crate
    /// (`workers/{domain}/`) so each worker gets its own `src/codelist/`
    /// covering exactly the codelists its routed DTO code references; the
    /// worker `lib.rs` declares `pub mod codelist;` unconditionally, so the
    /// module file is always emitted (header-only when nothing is referenced
    /// or the graph has no codelists at all).
    pub async fn generate_reexport_mod_for(
        &self,
        db: &dyn GraphQuerier,
        base: &Path,
        project: &ProjectConfig,
    ) -> Result<Vec<GeneratedFile>> {
        let codelists = db.list_codelists().await?;

        let codelist_dir = base.join("src").join("codelist");

        // Remove leftover local codelist .rs files (not mod.rs) so
        // generate_mod_files doesn't pick them up later.
        if codelist_dir.is_dir()
            && let Ok(entries) = std::fs::read_dir(&codelist_dir)
        {
            for entry in entries.flatten() {
                let path = entry.path();
                if path.extension().is_some_and(|e| e == "rs")
                    && path.file_name().is_some_and(|n| n != "mod.rs")
                {
                    let _ = std::fs::remove_file(&path);
                }
            }
        }

        // Build a set of all available codelist enum names.
        // Include empty codelists too — they have stub enums that DTO code may reference.
        let mut available: std::collections::HashSet<String> = std::collections::HashSet::new();
        for cl in &codelists {
            available.insert(cl.name.clone());
        }

        // Re-export exactly the codelists the crate's own code references
        // (`crate::codelist::<Name>`) — tight per-crate lists. The scan
        // covers the whole `src/` tree (skipping `src/codelist` itself):
        // beyond routed DTO code under `src/domain`/`src/api`, the root
        // placeholder crate references codelists from `src/events/
        // contracts.rs` and the loose `src/webhook_*.rs` modules, and a
        // per-dir allowlist would silently miss the next root module.
        let mut used: std::collections::BTreeSet<String> = std::collections::BTreeSet::new();
        let prefix = "crate::codelist::";
        let src_dir = base.join("src");
        if src_dir.is_dir() {
            scan_rs_files_for_prefix_except(&src_dir, prefix, "codelist", &mut used);
        }

        // Only re-export codelists that are both available and referenced.
        let mut content = String::from(&format!(
            "//! Codelist enum re-exports from {}.\n//! Generated by {} . DO NOT EDIT.\n\n",
            project.identity.domain_types_crate, project.identity.generator_name
        ));
        for name in &used {
            if available.contains(name.as_str()) {
                content.push_str(&format!(
                    "pub use {}::codelist::{};\n",
                    project.identity.domain_types_crate, name
                ));
            }
        }

        Ok(vec![GeneratedFile {
            path: codelist_dir.join("mod.rs"),
            content,
        }])
    }
}

/// Recursively scan `.rs` files under `dir` for occurrences of `prefix`
/// and collect the identifier that immediately follows each match.
/// Directories named `skip_dir` are pruned (used to exclude the re-export
/// module's own `codelist` directory from the scan).
fn scan_rs_files_for_prefix_except(
    dir: &std::path::Path,
    prefix: &str,
    skip_dir: &str,
    out: &mut std::collections::BTreeSet<String>,
) {
    let entries = match std::fs::read_dir(dir) {
        Ok(e) => e,
        Err(_) => return,
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            if path.file_name().is_some_and(|n| n == skip_dir) {
                continue;
            }
            scan_rs_files_for_prefix_except(&path, prefix, skip_dir, out);
        } else if path.extension().is_some_and(|e| e == "rs")
            && let Ok(content) = std::fs::read_to_string(&path)
        {
            for (idx, _) in content.match_indices(prefix) {
                let rest = &content[idx + prefix.len()..];
                let ident: String = rest
                    .chars()
                    .take_while(|c| c.is_ascii_alphanumeric() || *c == '_')
                    .collect();
                if !ident.is_empty() {
                    out.insert(ident);
                }
            }
        }
    }
}
